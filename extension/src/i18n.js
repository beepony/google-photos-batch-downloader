export function resolveLang(pref, uiLang = '') {
  if (pref === 'zh' || pref === 'en') return pref;
  return /^zh/i.test(uiLang || (typeof navigator !== 'undefined' ? navigator.language : '')) ? 'zh' : 'en';
}

export function t(lang, key, params = {}) {
  const table = MESSAGES[lang] || MESSAGES.en;
  const raw = table[key] ?? MESSAGES.en[key] ?? key;
  return String(raw).replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? `{${k}}`));
}

// Render a stored { k, p } message (or legacy plain string).
export function tm(lang, msg) {
  if (!msg) return '';
  if (typeof msg === 'string') return msg;
  return t(lang, msg.k, msg.p || {});
}
